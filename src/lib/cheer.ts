function hash(s: string) {
  let h = 0
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0
  return Math.abs(h)
}

export function cheerMessage(done: number, total: number, dateKey: string): string {
  if (!total) return '今日の習慣はお休み。のんびり過ごそう'
  const rate = done / total
  const band = done >= total ? 11 : done === 0 ? 0 : rate < 0.1 ? 1 : Math.min(10, Math.floor(rate * 10) + 1)
  const list = BANDS[band]
  return list[hash(`${dateKey}|${band}`) % list.length]
}
